import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const source = JSON.parse(fs.readFileSync(path.join(root, 'src/IBMFFonts/SolSans_75_MediumItalic.json'), 'utf8'));
for (const [field, value] of Object.entries({
    font: 'SolSans_75', face: 1, origin: 6, baseline: 18, width: 24, height: 24,
})) {
    if (source[field] !== value) throw new Error(`Unexpected ${field}`);
}
const entries = Object.entries(source.glyphs).sort(([a], [b]) => a.charCodeAt(0) - b.charCodeAt(0));
const rows = entries.map(([character, pixels]) => {
    if (character.length !== 1 || !Array.isArray(pixels) || !pixels.length) {
        throw new Error(`Invalid glyph ${character}`);
    }
    const masks = Array(24).fill(0);
    const seen = new Set();
    let right = -Infinity;
    for (const pixel of pixels) {
        if (!Array.isArray(pixel) || pixel.length !== 2 ||
            !pixel.every(n => Number.isInteger(n) && n >= 0 && n < 24) ||
            seen.has(String(pixel))) throw new Error(`Invalid pixel for ${character}`);
        seen.add(String(pixel));
        const [x, y] = pixel;
        masks[y] |= 1 << x;
        right = Math.max(right, x - source.origin);
    }
    return `    {${character.charCodeAt(0)}, ${right}, {${masks.map(n => `0x${n.toString(16)}u`).join(', ')}}}`;
});
const header = `// Generated by scripts/generate-italic-overrides.mjs; edit the JSON source instead.
#pragma once
#include <array>
#include <cstdint>

namespace solsans_italic {
struct Glyph {
    char32_t character;
    int right;
    std::array<uint32_t, 24> rows;
};
inline constexpr int ORIGIN = 6;
inline constexpr int BASELINE = 18;
inline constexpr std::array<Glyph, ${entries.length}> GLYPHS = {{
${rows.join(',\n')}
}};
}
`;
fs.writeFileSync(path.join(root, 'src/IBMFFonts/SolSans_75_MediumItalic.hpp'), header);
